    ok_R = abs(round(Rf, 5) - rep_R) < 10 ** -(dp) * 0.51 or round(Rf, dp) == rep_R
    ok = (c == rep_c) and (w == rep_w) and round(Rf, dp) == round(rep_R, dp)
    flag = "OK " if ok else "FAIL"
