def evaluate(vector):
    R = F(1)
    cost = 0
    weight = 0
    for i, part in enumerate(vector.split(","), start=1):
        q = F(1)  # prob subsystem fails = product of (1-r) over chosen comps
        for ch in part:
            r, c, w = SORTED[i][int(ch) - 1]
            q *= (1 - F(str(r)))
            cost += c
            weight += w
        R *= (1 - q)
    return R, cost, weight

